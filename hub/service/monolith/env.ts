import type { DrizzleEnvSchema } from "@saflib/drizzle/env";
import type { EnvEnvSchema } from "@saflib/env/env";
import type { ExpressEnvSchema } from "@saflib/express/env";
import type { NodeEnvSchema } from "@saflib/node/env";
import type { OryKratosHttpEnvSchema } from "@saflib/ory-kratos-http/env";
import type { VendorsInfisicalEnvSchema } from "@saflib/vendors-infisical/env";
import type { VendorsSentryNodeEnvSchema } from "@saflib/vendors-sentry-node/env";
import type { HubServiceEnvSchema } from "@sderickson/hub-service/env";
import type { HubServiceCommonEnvSchema } from "@sderickson/hub-service-common/env";

/**
 * Environment variables for the `@sderickson/hub-monolith` package, including inherited variables via `extends`.
 * Generated by `@saflib/env`. To update, make changes to the adjacent `env.schema.json`, navigate to the package root, and run `npm exec saf-env generate`.
 */
export interface HubMonolithEnvSchema
  extends
    DrizzleEnvSchema,
    EnvEnvSchema,
    ExpressEnvSchema,
    NodeEnvSchema,
    OryKratosHttpEnvSchema,
    VendorsInfisicalEnvSchema,
    VendorsSentryNodeEnvSchema,
    HubServiceEnvSchema,
    HubServiceCommonEnvSchema {}

/**
 * `process.env` casted to the `HubMonolithEnvSchema` type.
 */
export const typedEnv = (globalThis.process
  ? process.env
  : {}) as unknown as HubMonolithEnvSchema;
